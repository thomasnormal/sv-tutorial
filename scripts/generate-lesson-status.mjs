#!/usr/bin/env node

/**
 * Generate the reader-facing lesson status data from the item-16 census.
 *
 * The markdown table is deliberately the only hand-maintained status source.
 * Keeping this step in `prebuild` means a rebuilt site always reflects the
 * latest diagnostics and cannot retain a stale badge or status-page row.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import meta from '../src/lessons/meta.js';

const root = resolve(new URL('..', import.meta.url).pathname);
const sourcePath = resolve(root, 'docs/mox-bugs/mox-wasm-item16-failures.md');
const outputPath = resolve(root, 'src/lib/generated-lesson-status.js');

function cleanCell(value) {
  return value.trim().replace(/^`|`$/g, '');
}

function parseRows(markdown) {
  const rows = [];
  for (const line of markdown.split(/\r?\n/)) {
    if (!line.startsWith('| `')) continue;
    const cells = line.slice(1, line.lastIndexOf('|')).split('|').map(cleanCell);
    if (cells.length !== 6 || !cells[0].includes('/')) continue;
    const [slug, mode, construct, diagnostic, clause, status] = cells;
    rows.push({ slug, mode, construct, diagnostic, clause, status: status || 'Mox refusal' });
  }
  return rows;
}

const censusRows = parseRows(readFileSync(sourcePath, 'utf8'));
const rowsBySlug = new Map();
for (const row of censusRows) {
  if (!meta[row.slug]) throw new Error(`Status census references unknown lesson: ${row.slug}`);
  const rows = rowsBySlug.get(row.slug) ?? [];
  rows.push(row);
  rowsBySlug.set(row.slug, rows);
}

const rank = { PASS: 0, environment: 1, 'Mox refusal': 2 };
const entries = Object.entries(meta).map(([slug, lesson]) => {
  const rows = rowsBySlug.get(slug) ?? [{
    slug,
    mode: 'browser',
    construct: 'browser run/verify passed',
    diagnostic: '',
    clause: '—',
    status: 'PASS'
  }];
  const status = rows.reduce((best, row) =>
    (rank[row.status] ?? 0) > (rank[best] ?? 0) ? row.status : best, 'PASS');
  return { slug, title: lesson.title, status, rows };
});

const summary = entries.reduce((counts, entry) => {
  counts[entry.status] = (counts[entry.status] ?? 0) + 1;
  return counts;
}, { PASS: 0, 'Mox refusal': 0, environment: 0 });

const generated = `// Generated by scripts/generate-lesson-status.mjs; do not edit by hand.\n` +
  `export const lessonStatuses = ${JSON.stringify(entries, null, 2)};\n` +
  `export const statusSummary = ${JSON.stringify(summary, null, 2)};\n` +
  `export const lessonStatusBySlug = Object.fromEntries(lessonStatuses.map((entry) => [entry.slug, entry]));\n` +
  `export function statusForLesson(slug) { return lessonStatusBySlug[slug] ?? { slug, title: slug, status: 'PASS', rows: [] }; }\n`;

writeFileSync(outputPath, generated);
console.log(`Generated ${entries.length} lesson statuses (${censusRows.length} census rows) from ${sourcePath}`);
